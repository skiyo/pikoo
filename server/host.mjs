import { installContextLearning } from './context-runtime.mjs';
import { once } from 'node:events';
import { acquireGatewayLease } from 'qwen-audio-agent/gateway-lease';
import { createGatewayApplication } from 'qwen-audio-agent/gateway-application';
import { createRealtimeProviderRegistry } from 'qwen-audio-agent/realtime-provider';
import { config } from './node_modules/qwen-audio-agent/server/src/core/config.mjs';
import { pikooGoogleLiveProvider } from './google-live-compat.mjs';
import { familyToolsOptions } from './family-tools.mjs';
import { installCompanionInput } from './companion-runtime.mjs';
import { installSilentHistoryFilter } from './silence-output.mjs';
import path from 'node:path';
import { openAiLiveProvider } from './openai-live.mjs';
import { TerraClient } from './openai-terra.mjs';
import { UsageLedger } from './live-usage.mjs';
import { bindLiveRuntime,installLiveDiagnostics } from './live-runtime.mjs';
import { memoryDeadline } from './memory-timeout.mjs';
process.env.TZ='Asia/Shanghai';
installCompanionInput();
installSilentHistoryFilter();
const liveEnabled=process.env.PIKOO_VOICE_PROVIDER==='openai-live';
const ledger=liveEnabled?new UsageLedger({filePath:path.join(config.stateDirectory,'pikoo-openai-usage.json'),
 periodStart:process.env.PIKOO_CREDIT_PERIOD_START,periodEnd:process.env.PIKOO_CREDIT_PERIOD_END}):null;
const terra=liveEnabled?new TerraClient({ledger}):null;
const contextLearning=installContextLearning(liveEnabled?{textModelCall:terra.textCall('memory',memoryDeadline()),summaryTextCall:terra.textCall('summary',memoryDeadline())}:{});
const lease=acquireGatewayLease(config.stateDirectory,{owner:'pikoo-systemd'});
process.env.QWEN_AUDIO_GATEWAY_INSTANCE_ID=lease.instanceId;
process.env.QWEN_AUDIO_GATEWAY_STARTED_AT=new Date().toISOString();
const provider=liveEnabled?'openai-live':'google-live';
const diagnostics=liveEnabled?installLiveDiagnostics():null;
const app=createGatewayApplication({...familyToolsOptions(),autoStart:false,realtimeProviderRegistry:createRealtimeProviderRegistry({providers:[pikooGoogleLiveProvider,openAiLiveProvider],defaultProvider:provider}),realtimeProvider:provider});
if(liveEnabled)bindLiveRuntime(app,{terra,ledger,config,diagnostics});
contextLearning.bind(app);
app.start();
if(!app.server.listening)await once(app.server,'listening');
lease.update({state:'ready',origin:`http://127.0.0.1:${app.server.address().port}`});
const heartbeat=setInterval(()=>lease.update(),15000);heartbeat.unref();
let closing;
function stop(){
 if(closing)return closing;
 clearInterval(heartbeat);
 const timeout=setTimeout(()=>process.exit(1),80000);timeout.unref();
 closing=app.close().then(()=>{lease.release();process.exit(0)}).catch(e=>{console.error(e.message);lease.release();process.exit(1)});
 return closing;
}
process.once('SIGTERM',stop);process.once('SIGINT',stop);process.once('exit',()=>lease.release());
